from pathlib import Path

import joblib
import numpy as np
import pandas as pd
import streamlit as st

st.set_page_config(
    page_title="IoT Stress Monitor",
    page_icon="💓",
    layout="wide"
)

# Locate the trained model
PROJECT_ROOT = Path(__file__).resolve().parent.parent
MODEL_PATH = PROJECT_ROOT / "ml" / "stress_model.joblib"

st.title("IoT-Based Stress Monitoring System")

st.caption(
    "ESP32 and Machine Learning demonstration dashboard"
)

# Load the trained model
@st.cache_resource
def load_model(model_path):
    return joblib.load(model_path)


if not MODEL_PATH.exists():
    st.error(f"Trained model not found: {MODEL_PATH}")
    st.info("Run: python .\\ml\\train_model.py")
    st.stop()

try:
    model = load_model(str(MODEL_PATH))
except Exception as exc:
    st.error(f"Could not load the trained model: {exc}")
    st.stop()

st.sidebar.header("Simulation settings")

n = st.sidebar.slider(
    "Number of demo samples",
    min_value=10,
    max_value=60,
    value=30
)

seed = st.sidebar.number_input(
    "Simulation seed",
    min_value=0,
    max_value=100000,
    value=17
)

rng = np.random.default_rng(int(seed))
x = np.arange(n)

# Generate demonstration readings
heart_rate = np.clip(
    74 + 10 * np.sin(x / 5) + rng.normal(0, 2, n),
    55,
    115
)

temperature = np.clip(
    36.5
    + 0.2 * np.sin(x / 8)
    + rng.normal(0, 0.05, n),
    35.8,
    37.4
)

# Predict using the trained ML model
features = pd.DataFrame({
    "heart_rate": heart_rate,
    "temperature": temperature
})

predictions = model.predict(features)

df = pd.DataFrame({
    "Sample": x + 1,
    "Heart rate (BPM)": heart_rate.round(1),
    "Temperature (°C)": temperature.round(2),
    "Estimated level": predictions,
    "Data source": "SIMULATED",
    "Prediction method": "Random Forest ML"
})

# Latest readings
latest = df.iloc[-1]

col1, col2, col3 = st.columns(3)

col1.metric(
    "Latest heart rate",
    f"{latest['Heart rate (BPM)']:.1f} BPM"
)

col2.metric(
    "Latest temperature",
    f"{latest['Temperature (°C)']:.2f} °C"
)

col3.metric(
    "ML-predicted category",
    str(latest["Estimated level"])
)

st.warning(
    "Simulation mode is active. Readings are generated by software, "
    "not collected from physical sensors. The ML model was trained "
    "on a very small synthetic dataset. Its predictions are "
    "demonstrations, not medically validated stress assessments."
)

st.subheader("Heart-rate trend")

st.line_chart(
    df.set_index("Sample")[["Heart rate (BPM)"]]
)

st.subheader("Temperature trend")

st.line_chart(
    df.set_index("Sample")[["Temperature (°C)"]]
)

st.subheader("ML prediction distribution")

prediction_counts = (
    df["Estimated level"]
    .value_counts()
    .rename_axis("Predicted category")
    .to_frame("Number of samples")
)

st.bar_chart(prediction_counts)

st.subheader("Demonstration records")

st.dataframe(df, use_container_width=True)

csv_data = df.to_csv(index=False).encode("utf-8")

st.download_button(
    label="Download demonstration CSV",
    data=csv_data,
    file_name="stress_monitor_demo.csv",
    mime="text/csv"
)